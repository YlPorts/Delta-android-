#!/usr/bin/env python3
"""Generate Android palette from the ORIGINAL Delta iOS *.colorset resources.

Delta/Extensions/UIColor+Delta.swift references the named colors
Purple, LightPurple and DarkGray. Build-time extraction preserves their
sRGB components instead of approximating Apple's design colors by eye.

Fallbacks are strictly for missing/invalid iOS catalog entries and are
reported as warnings in GitHub Actions.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "android/app/src/main/java/com/ylports/deltaandroid/OriginalDeltaColors.kt"
FALLBACK = {
    "Purple": (121, 83, 231),
    "LightPurple": (186, 176, 241),
    "DarkGray": (16, 17, 21),
}
VALID = {"Purple", "LightPurple", "DarkGray"}


def component(value: object) -> int:
    s = str(value).strip()
    if not re.fullmatch(r"(?:0(?:\.\d+)?|1(?:\.0+)?|\.\d+)", s):
        raise ValueError(f"Unexpected color component: {s!r}")
    return max(0, min(255, round(float(s) * 255)))


def resolve(name: str) -> tuple[tuple[int, int, int], str]:
    matches = sorted((ROOT / "Delta").rglob(name + ".colorset/Contents.json"))
    for path in matches:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            colors = data.get("colors", [])
            candidates = [
                x for x in colors
                if x.get("idiom") in ("universal", None)
                and "color" in x
            ]
            if not candidates:
                continue
            dark = [
                x for x in candidates if any(
                    a.get("appearance") == "luminosity" and a.get("value") == "dark"
                    for a in x.get("appearances", [])
                )
            ]
            item = (dark or candidates)[0]["color"]
            components = item.get("components", {})
            if item.get("color-space") not in ("srgb", "display-p3", "extended-srgb"):
                continue
            rgb = tuple(component(components[k]) for k in ("red", "green", "blue"))
            return rgb, str(path.relative_to(ROOT))
        except (KeyError, ValueError, TypeError, OSError) as exc:
            print(f"WARNING: invalid iOS colorset {path}: {exc}", file=sys.stderr)
    print(f"WARNING: no usable original iOS asset for {name}; using fallback", file=sys.stderr)
    return FALLBACK[name], "fallback"


def main() -> None:
    colors = {name: resolve(name) for name in sorted(VALID)}
    output = [
        "// GENERATED at build time from Delta's original iOS color catalogs.",
        "// Do not edit; generated by android/tools/import_ios_colors.py.",
        "package com.ylports.deltaandroid",
        "",
        "import android.graphics.Color",
        "",
        "object OriginalDeltaColors {",
    ]
    for name, (rgb, source) in colors.items():
        key = name[0].lower() + name[1:]
        output.append(f"    // Source: {source}")
        output.append(f"    val {key}: Int = Color.rgb({rgb[0]}, {rgb[1]}, {rgb[2]})")
    output += ["}", ""]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(output), encoding="utf-8")
    for name, (rgb, source) in colors.items():
        print(f"Delta UIColor {name}: RGB={rgb}, asset={source}")


if __name__ == "__main__":
    main()
